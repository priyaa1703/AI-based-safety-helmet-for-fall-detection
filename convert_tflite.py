"""
convert_tflite.py
-----------------
Keras model -> float TFLite -> full-INT8 TFLite -> C array for ESP32.
Also compares size and test accuracy before / after quantization.

    python convert_tflite.py
"""

import json
import os
os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "2")

import numpy as np
import tensorflow as tf
from sklearn.metrics import accuracy_score, recall_score

from preprocess import prepare_data, CLASSES, MODELS, REPORTS, ROOT

ESP32_DIR = ROOT / "esp32"
FALL_ID = CLASSES.index("FALL")


def run_tflite(model_bytes, X):
    """Run a TFLite model on scaled float inputs and return class probabilities."""
    interp = tf.lite.Interpreter(model_content=model_bytes)
    interp.allocate_tensors()
    inp = interp.get_input_details()[0]
    out = interp.get_output_details()[0]
    probs = []
    for row in X:
        x = row.reshape(1, -1).astype(np.float32)
        if inp["dtype"] == np.int8:                       # quantize input
            scale, zp = inp["quantization"]
            x = np.clip(np.round(x / scale + zp), -128, 127).astype(np.int8)
        interp.set_tensor(inp["index"], x)
        interp.invoke()
        y = interp.get_tensor(out["index"])[0]
        if out["dtype"] == np.int8:                       # dequantize output
            scale, zp = out["quantization"]
            y = (y.astype(np.float32) - zp) * scale
        probs.append(y)
    return np.array(probs)


def bytes_to_c_header(data, var_name="helmet_model_data"):
    lines = []
    lines.append("// Auto-generated by convert_tflite.py - do not edit by hand.")
    lines.append("// INT8 TensorFlow Lite model for the miner safety helmet.")
    lines.append("// Input : 10 x int8, scaled with helmet_scaler.h then quantized (see sketch)")
    lines.append("// Output: 4 x int8 probabilities. Class order:")
    lines.append("//   0 NORMAL, 1 FALL, 2 HEALTH_ALERT, 3 ENVIRONMENT_ALERT")
    lines.append("#ifndef HELMET_MODEL_DATA_H")
    lines.append("#define HELMET_MODEL_DATA_H")
    lines.append("")
    lines.append(f"alignas(16) const unsigned char {var_name}[] = {{")
    for i in range(0, len(data), 12):
        chunk = ", ".join(f"0x{b:02x}" for b in data[i:i + 12])
        lines.append("  " + chunk + ",")
    lines.append("};")
    lines.append(f"const unsigned int {var_name}_len = {len(data)};")
    lines.append("")
    lines.append("#endif  // HELMET_MODEL_DATA_H")
    return "\n".join(lines) + "\n"


def main():
    data = prepare_data(verbose=False)
    X_train, X_test, y_test = data["X_train"], data["X_test"], data["y_test"]

    model = tf.keras.models.load_model(MODELS / "helmet_mlp.keras")

    # ---------- 1. plain float TFLite (reference) ----------
    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    float_bytes = conv.convert()
    (MODELS / "helmet_model_float.tflite").write_bytes(float_bytes)

    # ---------- 2. full INT8 ----------
    def representative_data():
        # a few hundred TRAINING rows so the converter can pick quantization ranges
        rng = np.random.default_rng(0)
        idx = rng.choice(len(X_train), 500, replace=False)
        for i in idx:
            yield [X_train[i:i + 1].astype(np.float32)]

    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    conv.optimizations = [tf.lite.Optimize.DEFAULT]
    conv.representative_dataset = representative_data
    conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    conv.inference_input_type = tf.int8
    conv.inference_output_type = tf.int8
    int8_bytes = conv.convert()
    (MODELS / "helmet_model.tflite").write_bytes(int8_bytes)

    # ---------- 3. C header ----------
    ESP32_DIR.mkdir(exist_ok=True)
    (ESP32_DIR / "helmet_model_data.h").write_text(bytes_to_c_header(int8_bytes))

    # ---------- 4. compare ----------
    keras_size = os.path.getsize(MODELS / "helmet_mlp.keras")
    results = {}
    keras_pred = model.predict(X_test, verbose=0)
    for name, probs in [("Keras (float32)", keras_pred),
                        ("TFLite float32", run_tflite(float_bytes, X_test)),
                        ("TFLite INT8", run_tflite(int8_bytes, X_test))]:
        pred = probs.argmax(1)
        results[name] = dict(
            accuracy=float(accuracy_score(y_test, pred)),
            fall_recall=float(recall_score(y_test, pred, labels=[FALL_ID], average=None)[0]),
        )

    interp = tf.lite.Interpreter(model_content=int8_bytes)
    interp.allocate_tensors()
    in_d, out_d = interp.get_input_details()[0], interp.get_output_details()[0]
    quant = {
        "input_scale": float(in_d["quantization"][0]), "input_zero_point": int(in_d["quantization"][1]),
        "output_scale": float(out_d["quantization"][0]), "output_zero_point": int(out_d["quantization"][1]),
    }

    sizes = {"keras_file_bytes": keras_size,
             "tflite_float_bytes": len(float_bytes),
             "tflite_int8_bytes": len(int8_bytes)}

    print("Sizes")
    print(f"  Keras .keras file : {keras_size:>7,d} bytes  (includes metadata, not a fair deployment size)")
    print(f"  TFLite float32    : {len(float_bytes):>7,d} bytes")
    print(f"  TFLite INT8       : {len(int8_bytes):>7,d} bytes  "
          f"({len(int8_bytes) / len(float_bytes):.0%} of float TFLite)")
    print("\nTest-set results")
    for name, r in results.items():
        print(f"  {name:16s} accuracy {r['accuracy']:.4f}   FALL recall {r['fall_recall']:.4f}")
    print("\nINT8 quantization parameters (needed on the ESP32):")
    for k, v in quant.items():
        print(f"  {k}: {v}")

    (REPORTS / "quantization_report.json").write_text(
        json.dumps({"sizes": sizes, "results": results, "quantization": quant}, indent=2))
    print(f"\nWrote models/helmet_model.tflite and esp32/helmet_model_data.h ({len(int8_bytes)} bytes)")

    # also write scaler + quant constants as a header for the sketch
    p = json.loads((MODELS / "scaler_params.json").read_text())
    arr = lambda v: ", ".join(f"{x:.6f}f" for x in v)
    h = f"""// Auto-generated by convert_tflite.py - do not edit by hand.
// Feature order: {", ".join(p['feature_order'])}
#ifndef HELMET_SCALER_H
#define HELMET_SCALER_H

#define N_FEATURES 10
#define N_CLASSES 4

// StandardScaler fitted on the TRAINING data only: x_scaled = (x - mean) / scale
const float FEATURE_MEAN[N_FEATURES]  = {{ {arr(p['mean'])} }};
const float FEATURE_SCALE[N_FEATURES] = {{ {arr(p['scale'])} }};

// Used only if a sensor returns nothing / garbage (same as the training imputer)
const float FEATURE_FALLBACK[N_FEATURES] = {{ {arr(p['fallback_values_for_missing'])} }};

// INT8 quantization of model input / output (also readable from the model at runtime)
const float INPUT_SCALE  = {quant['input_scale']:.9f}f;
const int   INPUT_ZERO_POINT = {quant['input_zero_point']};
const float OUTPUT_SCALE = {quant['output_scale']:.9f}f;
const int   OUTPUT_ZERO_POINT = {quant['output_zero_point']};

const char* CLASS_NAMES[N_CLASSES] = {{ "NORMAL", "FALL", "HEALTH_ALERT", "ENVIRONMENT_ALERT" }};

#endif  // HELMET_SCALER_H
"""
    (ESP32_DIR / "helmet_scaler.h").write_text(h)
    print("Wrote esp32/helmet_scaler.h")


if __name__ == "__main__":
    main()
